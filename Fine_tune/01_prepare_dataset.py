"""
Step 1: 準備資料集
==================
將 SRT 標註檔案轉換為 pyannote 訓練所需的格式

執行方式:
    python 01_prepare_dataset.py
"""

import os
import sys
import random
import shutil
from pathlib import Path

# 加入專案路徑
sys.path.insert(0, str(Path(__file__).parent))

from config import (
    RAW_DATA_DIR,
    PROCESSED_DATA_DIR,
    SPEAKER_MAPPING,
    VAL_RATIO,
    RANDOM_SEED,
    create_directories
)
from utils.srt_parser import SRTParser
from utils.rttm_converter import RTTMConverter
from utils.audio_utils import AudioUtils


def find_audio_file(folder: Path) -> Path:
    """
    在資料夾中尋找音訊檔案
    
    Args:
        folder: 資料夾路徑
        
    Returns:
        音訊檔案路徑
    """
    audio_extensions = ['.mp3', '.wav', '.flac', '.ogg', '.m4a']
    
    for ext in audio_extensions:
        files = list(folder.glob(f"*{ext}"))
        if files:
            return files[0]
    
    raise FileNotFoundError(f"在 {folder} 中找不到音訊檔案")


def find_srt_file(folder: Path) -> Path:
    """
    在資料夾中尋找 SRT 標註檔案
    
    優先順序: Aegisub.srt > GTruth.srt > 其他 .srt
    """
    # 優先使用 Aegisub.srt
    aegisub_srt = folder / "Aegisub.srt"
    if aegisub_srt.exists():
        return aegisub_srt
    
    # 其次使用 GTruth.srt
    gtruth_srt = folder / "GTruth.srt"
    if gtruth_srt.exists():
        return gtruth_srt
    
    # 最後尋找任何 .srt 檔案
    srt_files = list(folder.glob("*.srt"))
    if srt_files:
        return srt_files[0]
    
    raise FileNotFoundError(f"在 {folder} 中找不到 SRT 標註檔案")


def process_single_sample(
    folder: Path,
    output_dir: Path,
    file_id: str
) -> dict:
    """
    處理單個樣本
    
    Args:
        folder: 原始資料夾
        output_dir: 輸出目錄
        file_id: 檔案識別碼
        
    Returns:
        樣本資訊字典
    """
    # 尋找檔案
    audio_file = find_audio_file(folder)
    srt_file = find_srt_file(folder)
    
    print(f"  音訊檔: {audio_file.name}")
    print(f"  標註檔: {srt_file.name}")
    
    # 取得音訊時長
    duration = AudioUtils.get_duration(audio_file)
    if duration is None:
        raise ValueError(f"無法取得音訊時長: {audio_file}")
    
    print(f"  時長: {duration:.2f} 秒")
    
    # 解析 SRT
    segments = SRTParser.parse_file(srt_file)
    print(f"  段落數: {len(segments)}")
    
    # 顯示說話人統計
    stats = SRTParser.get_speaker_statistics(segments)
    for speaker, info in stats.items():
        print(f"    {speaker}: {info['count']} 段, {info['duration']:.2f} 秒")
    
    # 轉換為 RTTM
    rttm_path = output_dir / f"{file_id}.rttm"
    rttm_lines = RTTMConverter.srt_to_rttm(
        srt_file,
        output_path=rttm_path,
        file_id=file_id,
        speaker_mapping=SPEAKER_MAPPING
    )
    print(f"  RTTM 行數: {len(rttm_lines)}")
    
    # 建立 UEM 檔案
    uem_path = output_dir / f"{file_id}.uem"
    RTTMConverter.create_uem(file_id, duration, uem_path)
    
    # 複製或建立符號連結到音訊檔
    audio_link = output_dir / f"{file_id}{audio_file.suffix}"
    if not audio_link.exists():
        shutil.copy2(audio_file, audio_link)
    
    return {
        'file_id': file_id,
        'audio_path': str(audio_link),
        'rttm_path': str(rttm_path),
        'uem_path': str(uem_path),
        'duration': duration,
        'num_segments': len(segments),
        'speakers': list(stats.keys())
    }


def create_protocol_files(
    train_samples: list,
    val_samples: list,
    output_dir: Path
):
    """
    建立 pyannote 訓練所需的 protocol 檔案
    
    Args:
        train_samples: 訓練樣本列表
        val_samples: 驗證樣本列表
        output_dir: 輸出目錄
    """
    # 建立 database.yml
    database_yml = output_dir / "database.yml"
    
    yml_content = f"""# Pyannote Database Configuration
# Generated by prepare_dataset.py

Databases:
  ASD_Diarization: {output_dir}

Protocols:
  ASD_Diarization:
    SpeakerDiarization:
      finetune:
        train:
          uri: {output_dir / 'train.lst'}
          annotation: {output_dir / 'train.rttm'}
          annotated: {output_dir / 'train.uem'}
        development:
          uri: {output_dir / 'val.lst'}
          annotation: {output_dir / 'val.rttm'}
          annotated: {output_dir / 'val.uem'}
"""
    
    database_yml.write_text(yml_content, encoding='utf-8')
    print(f"✓ 已建立 database.yml")
    
    # 合併訓練集的 RTTM 和 UEM
    train_rttm = output_dir / "train.rttm"
    train_uem = output_dir / "train.uem"
    train_lst = output_dir / "train.lst"
    
    with open(train_rttm, 'w', encoding='utf-8') as f_rttm, \
         open(train_uem, 'w', encoding='utf-8') as f_uem, \
         open(train_lst, 'w', encoding='utf-8') as f_lst:
        
        for sample in train_samples:
            # 讀取並合併 RTTM
            rttm_content = Path(sample['rttm_path']).read_text(encoding='utf-8')
            f_rttm.write(rttm_content)
            
            # 讀取並合併 UEM
            uem_content = Path(sample['uem_path']).read_text(encoding='utf-8')
            f_uem.write(uem_content)
            
            # 寫入檔案清單
            f_lst.write(sample['file_id'] + '\n')
    
    print(f"✓ 已建立訓練集檔案 (train.rttm, train.uem, train.lst)")
    
    # 合併驗證集的 RTTM 和 UEM
    val_rttm = output_dir / "val.rttm"
    val_uem = output_dir / "val.uem"
    val_lst = output_dir / "val.lst"
    
    with open(val_rttm, 'w', encoding='utf-8') as f_rttm, \
         open(val_uem, 'w', encoding='utf-8') as f_uem, \
         open(val_lst, 'w', encoding='utf-8') as f_lst:
        
        for sample in val_samples:
            rttm_content = Path(sample['rttm_path']).read_text(encoding='utf-8')
            f_rttm.write(rttm_content)
            
            uem_content = Path(sample['uem_path']).read_text(encoding='utf-8')
            f_uem.write(uem_content)
            
            f_lst.write(sample['file_id'] + '\n')
    
    print(f"✓ 已建立驗證集檔案 (val.rttm, val.uem, val.lst)")


def main():
    """主程式"""
    print("=" * 60)
    print("Step 1: 準備資料集")
    print("=" * 60)
    
    # 建立目錄
    create_directories()
    
    # 尋找所有資料夾
    data_folders = [
        d for d in RAW_DATA_DIR.iterdir() 
        if d.is_dir() and not d.name.startswith('.')
    ]
    
    print(f"\n找到 {len(data_folders)} 個資料夾:")
    for folder in data_folders:
        print(f"  - {folder.name}")
    
    # 處理每個樣本
    all_samples = []
    
    for i, folder in enumerate(data_folders, 1):
        print(f"\n[{i}/{len(data_folders)}] 處理: {folder.name}")
        
        try:
            # 使用資料夾名稱作為 file_id
            file_id = folder.name.replace('-', '_')
            
            sample = process_single_sample(
                folder,
                PROCESSED_DATA_DIR,
                file_id
            )
            all_samples.append(sample)
            print(f"  ✓ 處理完成")
            
        except Exception as e:
            print(f"  ✗ 處理失敗: {e}")
            continue
    
    if not all_samples:
        print("\n❌ 沒有成功處理任何樣本!")
        return
    
    # 分割訓練集和驗證集
    random.seed(RANDOM_SEED)
    random.shuffle(all_samples)
    
    val_size = max(1, int(len(all_samples) * VAL_RATIO))
    val_samples = all_samples[:val_size]
    train_samples = all_samples[val_size:]
    
    # 如果樣本太少，訓練集和驗證集都使用全部
    if len(all_samples) <= 2:
        train_samples = all_samples
        val_samples = all_samples
    
    print(f"\n資料集分割:")
    print(f"  訓練集: {len(train_samples)} 個樣本")
    print(f"  驗證集: {len(val_samples)} 個樣本")
    
    # 建立 protocol 檔案
    print(f"\n建立 protocol 檔案...")
    create_protocol_files(train_samples, val_samples, PROCESSED_DATA_DIR)
    
    # 儲存樣本清單
    import json
    samples_json = PROCESSED_DATA_DIR / "samples.json"
    with open(samples_json, 'w', encoding='utf-8') as f:
        json.dump({
            'train': train_samples,
            'val': val_samples
        }, f, ensure_ascii=False, indent=2)
    print(f"✓ 已儲存樣本清單: {samples_json}")
    
    # 統計
    total_duration = sum(s['duration'] for s in all_samples)
    print(f"\n" + "=" * 60)
    print(f"✅ 資料準備完成!")
    print(f"  總樣本數: {len(all_samples)}")
    print(f"  總時長: {total_duration / 60:.1f} 分鐘")
    print(f"  輸出目錄: {PROCESSED_DATA_DIR}")
    print("=" * 60)


if __name__ == "__main__":
    main()
